"""
Read-only reconciliation of the metadata CSV against the call records, and a
dry run of R1 (calling hours) over the result.

Nothing in this module reads or writes a database: it compares plain
dictionaries, so it can be tested on scratch data and fed from a read-only
connection. It proposes changes; it never applies them.

Source of truth for a call's start time
---------------------------------------
metadata.csv. It is the ingestion format the application itself validates
(upload_service), the assignment names metadata as R1's input, and the labelled
R1 expectations were written against it. The database values for the 20
role-play calls were not entered from it: seed_db.py builds them as
`datetime.now() + timedelta(hours=<intended hour>)`, which adds the intended
hour to the seeding machine's clock time instead of setting the time of day.
Other columns (caller, office, account type, language) are reported but no
value is proposed for them: they do not affect R1 and the CSV is not
demonstrably right about them either.
"""

import csv
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional

from app.rules import R1_OK, R1_UNRESOLVED, R1_VIOLATION, R1Evaluation, evaluate_r1
from app.services.upload_service import _try_parse_timestamp

RECORDING_PRESENT = "present"
RECORDING_MISSING_FILE = "missing_file"  # the record says there is a recording; the file is not there
RECORDING_NOT_EXPECTED = "not_expected"  # the record says there is no recording

FIELDS_WITH_PROPOSAL = {"start_time"}
COMPARED_FIELDS = ("start_time", "caller_id", "office_id", "account_type", "language")

# Result of comparing one call's R1 outcome before and after the proposed correction.
AGREE = "agree"
CHANGE = "change_requires_approval"
UNRESOLVED = "unresolved"


@dataclass
class Discrepancy:
    field: str
    csv_value: Optional[str]
    db_value: Optional[str]
    proposed_value: Optional[str]  # None = no change proposed (decision needed)
    reason: str


@dataclass
class CallAudit:
    call_id: str
    csv_row: Optional[dict]
    db_row: Optional[dict]
    recording: str
    discrepancies: list = field(default_factory=list)
    problems: list = field(default_factory=list)  # missing/duplicate/invalid metadata
    r1_db: Optional[R1Evaluation] = None
    r1_csv: Optional[R1Evaluation] = None


def load_csv_rows(path) -> list:
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _db_start(db_row: dict) -> Optional[datetime]:
    value = db_row.get("start_time")
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value)) if value else None
    except ValueError:
        return None


def recording_state(db_row: Optional[dict], csv_row: Optional[dict], audio_dir: Path) -> str:
    """Whether the recording EXISTS, judged the way the pipeline finds it
    (the base name of the stored audio path inside the audio directory), never
    from the has_audio flag alone."""
    name = None
    if db_row and db_row.get("audio_path"):
        name = Path(db_row["audio_path"]).name
    elif csv_row and csv_row.get("filename"):
        name = Path(csv_row["filename"]).name
    flagged = bool(db_row and db_row.get("has_audio"))
    if name and (Path(audio_dir) / name).is_file():
        return RECORDING_PRESENT
    return RECORDING_MISSING_FILE if (flagged or (csv_row and not db_row)) else RECORDING_NOT_EXPECTED


def _reason_for_start_time(csv_dt: Optional[datetime], db_dt: Optional[datetime]) -> str:
    if csv_dt is None:
        return "The CSV start time is missing or not a full date-time, so nothing can be proposed."
    if db_dt is None:
        return "The database start time is missing or unreadable; the CSV value is proposed."
    return (
        "The database value was generated by the seed script, not entered from metadata.csv; "
        "the CSV is the proposed source of truth for start times."
    )


def audit_calls(csv_rows: list, db_rows: dict, audio_dir, expected_ids: list) -> list:
    """
    csv_rows   rows from metadata.csv (dicts)
    db_rows    {call_id: dict of the call record's columns}
    expected_ids  every call id that should exist (e.g. CALL-0001..CALL-0020)
    """
    by_csv: dict = {}
    duplicates: set = set()
    for row in csv_rows:
        call_id = (row.get("call_id") or "").strip()
        if not call_id:
            continue
        if call_id in by_csv:
            duplicates.add(call_id)
        by_csv.setdefault(call_id, row)

    audits = []
    for call_id in expected_ids:
        csv_row, db_row = by_csv.get(call_id), db_rows.get(call_id)
        audit = CallAudit(call_id, csv_row, db_row, recording_state(db_row, csv_row, Path(audio_dir)))

        if csv_row is None:
            audit.problems.append("missing metadata: no row for this call in the CSV")
        if db_row is None:
            audit.problems.append("missing record: no call record in the database")
        if call_id in duplicates:
            audit.problems.append("duplicate metadata: the CSV has more than one row for this call")

        csv_dt = _try_parse_timestamp(csv_row.get("start_time")) if csv_row else None
        db_dt = _db_start(db_row) if db_row else None
        if csv_row is not None and csv_dt is None:
            audit.problems.append(f"invalid timestamp in the CSV: {csv_row.get('start_time')!r}")
        if db_row is not None and db_dt is None:
            audit.problems.append(f"invalid timestamp in the database: {db_row.get('start_time')!r}")

        audit.r1_csv = evaluate_r1(csv_dt)
        audit.r1_db = evaluate_r1(db_dt)

        if csv_row is not None and db_row is not None:
            for name in COMPARED_FIELDS:
                csv_value = csv_row.get(name)
                db_value = db_row.get(name)
                if name == "start_time":
                    csv_text = csv_dt.isoformat() if csv_dt else csv_value
                    db_text = db_dt.isoformat() if db_dt else (str(db_value) if db_value is not None else None)
                    same = csv_dt is not None and db_dt is not None and csv_dt == db_dt
                    proposed = csv_dt.isoformat() if csv_dt else None
                    reason = _reason_for_start_time(csv_dt, db_dt)
                else:
                    csv_text, db_text = csv_value, db_value
                    same = (csv_value or None) == (db_value or None)
                    proposed = None
                    reason = "Does not affect R1; no value is proposed until you decide which source is right."
                if not same:
                    audit.discrepancies.append(Discrepancy(name, csv_text, db_text, proposed, reason))
        audits.append(audit)
    return audits


def office_conflicts(csv_rows: list, user_offices: dict) -> list:
    """CSV rows whose office_id is not the office of the caller named in the
    same row. (The upload validation only checks that each exists.)"""
    out = []
    for row in csv_rows:
        caller_office = user_offices.get((row.get("caller_id") or "").strip())
        if caller_office is not None and caller_office != (row.get("office_id") or "").strip():
            out.append({"call_id": row.get("call_id"), "caller_id": row.get("caller_id"), "csv_office": row.get("office_id"), "caller_office": caller_office})
    return out


def seed_offset(csv_dt: datetime, db_dt: datetime) -> timedelta:
    """The time-of-day difference between a stored start time and the intended
    one. The seed bug adds the seeding machine's clock time of day, so for the
    hard-coded calls this is the same constant for every call."""
    def tod(d):
        return timedelta(hours=d.hour, minutes=d.minute, seconds=d.second, microseconds=d.microsecond)
    return tod(db_dt) - tod(csv_dt)


def r1_dry_run(audits: list, labels: Optional[dict] = None) -> list:
    """One row per call: the R1 result the application would produce today
    (from the database time) beside the one the CSV time gives, and whether
    the correction would change it. `labels` optionally maps call id to the
    expected R1 value (script-derived labels, not audio-verified)."""
    rows = []
    for a in audits:
        current, proposed = a.r1_db, a.r1_csv
        if current.status == R1_UNRESOLVED or proposed.status == R1_UNRESOLVED:
            verdict, why = UNRESOLVED, "A start time is missing or invalid, so R1 cannot be determined."
        elif current.status == proposed.status:
            verdict = AGREE
            why = "Same result from both times." if not a.discrepancies else "Same R1 result from both times; the times themselves differ."
        else:
            verdict = CHANGE
            why = "The stored time gives a different R1 result than the CSV time; correcting the start time changes it."
        rows.append(
            {
                "call_id": a.call_id,
                "db_start": a.db_row.get("start_time") if a.db_row else None,
                "csv_start": a.csv_row.get("start_time") if a.csv_row else None,
                "recording": a.recording,
                "current_r1": current.status,
                "proposed_r1": proposed.status,
                "verdict": verdict,
                "reason": why,
                "expected_label": (labels or {}).get(a.call_id),
            }
        )
    return rows


# --- the metadata-only calls (no CSV exists for them) -----------------------------------------------------------


def _time_of_day(d: datetime) -> timedelta:
    return timedelta(hours=d.hour, minutes=d.minute, seconds=d.second, microseconds=d.microsecond)


def audit_metadata_only(rows: list, business_hours=(8, 18)) -> dict:
    """
    Read-only analysis of calls that have no metadata.csv row, testing ONE
    explanation: the seeder stored `capture_clock_time_of_day + <time of day in
    business hours>`. Under it every stored value equals T0 + x with x in
    [business start, business end], so the data alone bound T0:

        max(stored) - end_of_business  <=  T0  <=  min(stored) - start_of_business

    and, because the seeder captured the clock once, all rows share one
    microsecond value. If the bound is empty, or the rows disagree on the
    microsecond, the explanation is rejected and nothing is claimed.

    Nothing is changed and no replacement time is proposed here: this only says
    whether R1 as stored for these calls can be explained as an artifact, and
    how far the original times of day can be pinned down.
    """
    stored = [_db_start(r) for r in rows]
    parsed = [s for s in stored if s is not None]
    statuses = [evaluate_r1(s).status for s in parsed]
    lo_hour, hi_hour = business_hours
    start, end = timedelta(hours=lo_hour), timedelta(hours=hi_hour, minutes=59, seconds=59)

    result = {
        "calls": len(rows),
        "unreadable_start_times": len(rows) - len(parsed),
        "r1_as_stored": {k: statuses.count(k) for k in (R1_OK, R1_VIOLATION, R1_UNRESOLVED)},
        "explanation_holds": False,
    }
    if not parsed:
        return result

    microseconds = {s.microsecond for s in parsed}
    result["distinct_microsecond_values"] = len(microseconds)
    tods = [_time_of_day(s) for s in parsed]
    # A clock time of day cannot be negative, so the lower bound is clamped at zero.
    low, high = max(max(tods) - end, timedelta(0)), min(tods) - start
    result["clock_offset_bounds"] = [str(low), str(high)]
    result["clock_offset_window_seconds"] = (high - low).total_seconds()
    if len(microseconds) != 1 or high < low:
        return result

    # Check the conclusion at both ends of the window: it must not depend on where in it the truth lies.
    def hours_under(offset):
        return {((t - offset).seconds // 3600) for t in tods}

    hours_low, hours_high = hours_under(low), hours_under(high)
    in_hours = all(lo_hour <= h <= hi_hour for h in hours_low | hours_high)
    result.update(
        {
            "explanation_holds": in_hours,
            "original_hours_if_offset_at_low_end": sorted(hours_low),
            "original_hours_if_offset_at_high_end": sorted(hours_high),
            "originally_in_permitted_hours": len(parsed) if in_hours else None,
            "stored_r1_violations_explained_as_artifact": statuses.count(R1_VIOLATION) if in_hours else None,
            "date_range": [min(s.date() for s in parsed).isoformat(), max(s.date() for s in parsed).isoformat()],
            "original_time_precision_seconds": result["clock_offset_window_seconds"],
        }
    )
    return result
